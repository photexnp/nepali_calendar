// Regenerates nepali_calendar/bs_data.json from the nepali-date-converter npm package,
// so the Python (print) and JavaScript (desk) converters use the same month-length table.
// Run from the app root: node scripts/generate_bs_data.mjs
import { writeFileSync } from "node:fs";
import NepaliDate, { dateConfigMap } from "nepali-date-converter";

import { MONTH_KEYS, BS_YEARS, bs_to_ad } from "../nepali_calendar/public/js/bs.js";

const data = {
	_source: "Generated by scripts/generate_bs_data.mjs from nepali-date-converter; do not edit by hand.",
	epoch: { bs: [BS_YEARS[0], 1, 1], ad: bs_to_ad(BS_YEARS[0], 0, 1) },
	month_names: {
		en: MONTH_KEYS.map((_, m) => new NepaliDate(BS_YEARS[0], m, 1).format("MMMM", "en")),
		np: MONTH_KEYS.map((_, m) => new NepaliDate(BS_YEARS[0], m, 1).format("MMMM", "np")),
	},
	month_lengths: Object.fromEntries(
		BS_YEARS.map((year) => [year, MONTH_KEYS.map((key) => dateConfigMap[year][key])])
	),
};

const out = new URL("../nepali_calendar/bs_data.json", import.meta.url);
writeFileSync(out, JSON.stringify(data, null, "\t") + "\n");
console.log(`wrote ${out.pathname}: BS ${BS_YEARS[0]}–${BS_YEARS.at(-1)}, epoch ${data.epoch.ad}`);
